# File extensions that carry binary (image) content when collected from the sandbox.
IMAGE_OUTPUT_EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp", ".svg", ".gif"}


class GeneratedFileReferenceError(ValueError):
    """Raised when a code step references generated files that cannot be used as inputs."""


class GeneratedFile(NamedTuple):
    """A file produced by a successful code step earlier in the same research request."""

    source_step: int
    filename: str
    # Full original file content: raw decoded text for text files, base64 string for images.
    b64_data: str


def is_image_output_file(filename: str) -> bool:
    return Path(filename).suffix.lower() in IMAGE_OUTPUT_EXTENSIONS


def resolve_generated_file_references(
    selected_references: Any,
    available_files: List[GeneratedFile],
    step_status: Dict[int, Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """
    Validate code step references to files generated earlier in the same research request.

    Only files recorded in available_files (produced by successful code steps of the
    current request) can be resolved. References to non-existent files, failed or
    non-code steps, or steps from other requests raise a GeneratedFileReferenceError
    describing why the reference cannot be used.
    """
    if selected_references is None:
        return []
    if not isinstance(selected_references, list) or not selected_references:
        raise GeneratedFileReferenceError(
            "The input_files argument must be a non-empty list of files generated by "
            "earlier, successful code steps in this research request."
        )

    normalized_references: List[tuple] = []
    for reference in selected_references:
        if not isinstance(reference, dict):
            raise GeneratedFileReferenceError(
                f'Each entry in input_files must be an object with "filename" and "source_step", got: {reference}.'
            )
        filename = reference.get("filename")
        source_step = reference.get("source_step")
        if not isinstance(filename, str) or not filename.strip():
            raise GeneratedFileReferenceError(f'Each input_files entry needs a string "filename", got: {reference}.')
        if isinstance(source_step, bool) or not isinstance(source_step, int):
            raise GeneratedFileReferenceError(
                f'Each input_files entry needs an integer "source_step" (the step that generated the file), got: {reference}.'
            )
        normalized_references.append((source_step, filename))

    resolved_files: List[Dict[str, Any]] = []
    for source_step, filename in normalized_references:
        match = next(
            (
                generated_file
                for generated_file in available_files
                if generated_file.source_step == source_step and generated_file.filename == filename
            ),
            None,
        )
        if match is not None:
            resolved_files.append(match._asdict())
            continue

        # Build a precise reason so the researcher can correct the reference.
        status = step_status.get(source_step)
        if status is None:
            reason = (
                "this step has not completed in the current research request; only files from "
                "successful code steps of the same request can be selected"
            )
        elif status.get("name") != ConversationCommand.PythonCoder.value:
            reason = f"this step used the {status.get('name')} tool, which does not generate code output files"
        elif status.get("warning") or not status.get("success"):
            failure = status.get("warning") or "the code did not execute successfully"
            reason = f"this code step failed, so its files cannot be reused ({failure})"
        elif not status.get("files"):
            reason = "this code step completed but did not produce any output files"
        else:
            available = ", ".join(f'"{name}"' for name in status["files"])
            reason = f'it did not generate "{filename}". Files generated by that step: {available}'
        raise GeneratedFileReferenceError(f'Cannot reuse "{filename}" from step {source_step}: {reason}.')

    return resolved_files


def assign_generated_file_aliases(
    selected_files: List[Dict[str, Any]], reserved_user_filenames: set
) -> List[Dict[str, Any]]:
    """
    Pick collision-free sandbox filenames for generated files selected as inputs.

    Generated files must never overwrite each other or input files corresponding to
    the user's indexed documents. When the original name clashes, a step-prefixed
    (and then numbered) alias is assigned.
    """
    taken_filenames = {os.path.basename(name) for name in reserved_user_filenames if name}
    aliased_files: List[Dict[str, Any]] = []
    for selected in sorted(selected_files, key=lambda f: (f["source_step"], f["filename"])):
        original_name = os.path.basename(selected["filename"])
        stem, suffix = os.path.splitext(original_name)
        candidate = original_name
        if candidate in taken_filenames:
            candidate = f"{stem}_step{selected['source_step']}{suffix}"
        unique_candidate = candidate
        dedupe = 1
        while unique_candidate in taken_filenames:
            unique_candidate = f"{os.path.splitext(candidate)[0]}_{dedupe}{suffix}"
            dedupe += 1
        taken_filenames.add(unique_candidate)
        aliased_files.append({**selected, "sandbox_filename": unique_candidate})
    return aliased_files


def encode_generated_file_for_sandbox(generated_file: Dict[str, Any]) -> Dict[str, str]:
    """
    Convert a generated output file to the sandbox input payload format (base64).

    Images already hold base64 encoded binary content; text files hold the full raw
    decoded text and are re-encoded as base64, preserving the complete file content.
    """
    if is_image_output_file(generated_file["filename"]):
        b64_data = generated_file["b64_data"]
    else:
        b64_data = base64.b64encode(generated_file["b64_data"].encode("utf-8")).decode("utf-8")
    return {"filename": generated_file["sandbox_filename"], "b64_data": b64_data}


def build_generated_files_context(aliased_files: List[Dict[str, Any]]) -> str:
    """Describe selected generated files for the code generation LLM prompt."""
    if not aliased_files:
        return ""
    lines = [
        "The following files generated by earlier, successful code steps in this research are already saved in the sandbox.",
        "Read them in your program using the exact filenames given below (relative to the working directory).",
        "Do not recreate, re-download or paste the contents of these files.",
    ]
    for generated_file in aliased_files:
        file_type = "an image" if is_image_output_file(generated_file["filename"]) else "a text"
        lines.append(
            f'- "{generated_file["sandbox_filename"]}": {file_type} file originally named '
            f'"{os.path.basename(generated_file["filename"])}", generated in step {generated_file["source_step"]}.'
        )
    return "\n".join(lines)


def format_generated_files_for_planning(available_files: List[GeneratedFile]) -> str:
    """List reusable generated files (filename + source step) for the planner LLM."""
    if not available_files:
        return ""
    files_by_step: Dict[int, List[str]] = {}
    for generated_file in available_files:
        files_by_step.setdefault(generated_file.source_step, []).append(generated_file.filename)
    lines = [
        "# Files Available From Earlier Code Steps",
        "The files below were generated by successful code steps earlier in this request.",
        'To use a file\'s complete original content (text or image) in a later code step, pass it to the run_code tool\'s "input_files" argument using its exact "filename" and "source_step".',
        "Do not reconstruct file content from the summarized results and do not re-run the step that generated the file.",
        "Files with the same name from different steps are distinct and can each be selected independently.",
    ]
    for source_step in sorted(files_by_step):
        for filename in sorted(files_by_step[source_step]):
            file_type = "image" if is_image_output_file(filename) else "text"
            lines.append(f'- Step {source_step}: "{filename}" ({file_type})')
    return "\n".join(lines)


class GeneratedCode(NamedTuple):
    code: str
    input_files: List[FileObject]


async def run_code(
    instructions: str,
    conversation_history: List[ChatMessageModel],
    context: str,
    location_data: LocationData,
    user: KhojUser,
    send_status_func: Optional[Callable] = None,
    query_images: List[str] = None,
    query_files: str = None,
    relevant_memories: List[UserMemory] = None,
    agent: Agent = None,
    sandbox_url: str = SANDBOX_URL,
    tracer: dict = {},
    generated_input_files: Optional[List[Dict[str, Any]]] = None,
):
    # Fetch the user's indexed files once, both to reserve their filenames in the
    # sandbox and to infer which files the generated code needs access to.
    user_file_objects = await sync_to_async(list)(FileObjectAdapters.get_all_file_objects(user))

    # Files explicitly selected from successful code steps earlier in this research.
    # Assign collision-free sandbox names before code generation so the generated
    # code can reference the exact filenames provided in its prompt.
    if generated_input_files:
        generated_with_aliases = assign_generated_file_aliases(
            generated_input_files,
            reserved_user_filenames={f.file_name for f in user_file_objects},
        )
        generated_files_context = build_generated_files_context(generated_with_aliases)
    else:
        generated_with_aliases = []
        generated_files_context = ""

    # Generate Code
    if send_status_func:
        async for event in send_status_func(f"**Generate code snippet** for {instructions}"):
            yield {ChatEvent.STATUS: event}
    try:
        with timer("Chat actor: Generate programs to execute", logger):
            generated_code = await generate_python_code(
                instructions,
                conversation_history,
                context,
                location_data,
                user,
                query_images,
                agent,
                tracer,
                query_files,
                relevant_memories,
                user_file_objects=user_file_objects,
                generated_files_context=generated_files_context,
            )
    except Exception as e:
        raise ValueError(f"Failed to generate code for {instructions} with error: {e}")

    # Prepare Input Data
    input_data = []
    reserved_input_filenames = set()
    for f in generated_code.input_files:
        input_data.append(
            {
                "filename": f.file_name,
                "b64_data": base64.b64encode(f.raw_text.encode("utf-8")).decode("utf-8"),
            }
        )
        reserved_input_filenames.add(f.file_name)

    # Add selected generated files with their full original content (never rebuilt
    # from truncated summaries). Aliases guarantee no name collisions with user files.
    for generated_file in generated_with_aliases:
        if generated_file["sandbox_filename"] in reserved_input_filenames:
            logger.warning(
                f'Skipping generated file "{generated_file["sandbox_filename"]}" as it collides with an indexed input file.'
            )
            continue
        input_data.append(encode_generated_file_for_sandbox(generated_file))
        reserved_input_filenames.add(generated_file["sandbox_filename"])

    # Run Code
    if send_status_func:
        async for event in send_status_func("**Running code snippet**"):
            yield {ChatEvent.STATUS: event}
    try:
        with timer("Chat actor: Execute generated program", logger, log_level=logging.INFO):
            result = await execute_sandboxed_python(generated_code.code, input_data, sandbox_url)
            code = result.pop("code")
            cleaned_result = truncate_code_context({"cleaned": {"results": result}})["cleaned"]["results"]
            logger.info(f"Executed Code\n----\n{code}\n----\nResult\n----\n{cleaned_result}\n----")
            yield {instructions: {"code": code, "results": result}}
    except asyncio.TimeoutError as e:
        # Call the sandbox_url/stop GET API endpoint to stop the code sandbox
        error = f"Failed to run code for {instructions} with Timeout error: {e}"
        try:
            await aiohttp.ClientSession().get(f"{sandbox_url}/stop", timeout=5)
        except Exception as e:
            error += f"\n\nFailed to stop code sandbox with error: {e}"
        raise ValueError(error)
    except Exception as e:
        raise ValueError(f"Failed to run code for {instructions} with error: {e}")


async def generate_python_code(
    instructions: str,
    chat_history: List[ChatMessageModel],
    context: str,
    location_data: LocationData,
    user: KhojUser,
    query_images: list[str] = None,
    agent: Agent = None,
    tracer: dict = {},
    query_files: str = None,
    relevant_memories: List[UserMemory] = None,
    user_file_objects: List[FileObject] = None,
    generated_files_context: str = "",
) -> GeneratedCode:
    location = f"{location_data}" if location_data else "Unknown"
    username = prompts.user_name.format(name=user.get_full_name()) if user.get_full_name() else ""
    chat_history_str = construct_chat_history(chat_history)

    utc_date = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    personality_context = (
        prompts.personality_context.format(personality=agent.personality) if agent and agent.personality else ""
    )

    # add sandbox specific context like available packages
    sandbox_context = (
        prompts.e2b_sandbox_context if is_e2b_code_sandbox_enabled() else prompts.terrarium_sandbox_context
    )
    personality_context = f"{sandbox_context}\n{personality_context}"
    network_access_context = "**NO** " if not is_e2b_code_sandbox_enabled() else ""

    code_generation_prompt = prompts.python_code_generation_prompt.format(
        instructions=instructions,
        chat_history=chat_history_str,
        context=context,
        has_network_access=network_access_context,
        home_dir=HOME_DIR,
        current_date=utc_date,
        location=location,
        username=username,
        personality_context=personality_context,
        generated_files_context=generated_files_context,
    )

    agent_chat_model = AgentAdapters.get_agent_chat_model(agent, user) if agent else None

    response = await send_message_to_model_wrapper(
        code_generation_prompt,
        query_files=query_files,
        query_images=query_images,
        relevant_memories=relevant_memories,
        fast_model=False,
        agent_chat_model=agent_chat_model,
        user=user,
        tracer=tracer,
    )

    # Extract python code wrapped in markdown code blocks from the response
    code_blocks = re.findall(r"```(?:python)?\n(.*?)```", response.text, re.DOTALL)

    if not code_blocks:
        raise ValueError("No Python code blocks found in response")

    # Join multiple code blocks with newlines and strip any leading/trailing whitespace
    code = "\n".join(code_blocks).strip()

    if not isinstance(code, str) or is_none_or_empty(code):
        raise ValueError

    # Infer user files required in sandbox based on user file paths mentioned in code
    input_files: List[FileObject] = []
    if user_file_objects is None:
        user_file_objects = await sync_to_async(list)(FileObjectAdapters.get_all_file_objects(user))
    for user_file in user_file_objects:
        if user_file.file_name in code:
            # Replace references to full file path used in code with just the file basename to ease reference in sandbox
            file_basename = os.path.basename(user_file.file_name)
            code = code.replace(user_file.file_name, file_basename)
            user_file.file_name = file_basename
            input_files.append(user_file)

    return GeneratedCode(code, input_files)


@retry(
    retry=(
        retry_if_exception_type(aiohttp.ClientError)
        | retry_if_exception_type(aiohttp.ClientTimeout)
        | retry_if_exception_type(asyncio.TimeoutError)
        | retry_if_exception_type(ConnectionError)
        | retry_if_exception_type(httpx.RemoteProtocolError)
        | retry_if_exception_type(httpx.NetworkError)
        | retry_if_exception_type(httpx.TimeoutException)
    ),
    wait=wait_random_exponential(min=1, max=5),
    stop=stop_after_attempt(3),
    before_sleep=before_sleep_log(logger, logging.DEBUG),
    reraise=True,
)
async def execute_sandboxed_python(code: str, input_data: list[dict], sandbox_url: str = SANDBOX_URL) -> dict[str, Any]:
    """
    Takes code to run as a string and calls the terrarium API to execute it.
    Returns the result of the code execution as a dictionary.

    Reference data i/o format based on Terrarium example client code at:
    https://github.com/cohere-ai/cohere-terrarium/blob/main/example-clients/python/terrarium_client.py
    """
    cleaned_code = clean_code_python(code)
    if is_e2b_code_sandbox_enabled():
        try:
            return await execute_e2b(cleaned_code, input_data)
        except ImportError:
            pass
    return await execute_terrarium(cleaned_code, input_data, sandbox_url)


async def execute_e2b(code: str, input_files: list[dict]) -> dict[str, Any]:
    """Execute code and handle file I/O in e2b sandbox"""
    from e2b_code_interpreter import AsyncSandbox

    sandbox = await AsyncSandbox.create(
        api_key=os.getenv("E2B_API_KEY"),
        template=os.getenv("E2B_TEMPLATE", DEFAULT_E2B_TEMPLATE),
        timeout=120,
        request_timeout=30,
    )

    try:
        # Upload input files in parallel
        upload_tasks = [
            sandbox.files.write(file["filename"], base64.b64decode(file["b64_data"])) for file in input_files
        ]
        await asyncio.gather(*upload_tasks)

        # Note stored files before execution to identify new files created during execution
        E2bFile = NamedTuple("E2bFile", [("name", str), ("path", str)])
        original_files = {E2bFile(f.name, f.path) for f in await sandbox.files.list(HOME_DIR, depth=1)}

        # Execute code from main.py file
        execution = await sandbox.run_code(code=code, timeout=60)

        # Collect output files
        output_files = []
        image_file_ext = {".png", ".jpeg", ".jpg", ".svg"}

        # Identify new files created during execution
        new_files = set(E2bFile(f.name, f.path) for f in await sandbox.files.list(HOME_DIR, depth=1)) - original_files

        # Read newly created files in parallel
        def read_format(f):
            return "bytes" if Path(f.name).suffix in image_file_ext else "text"

        download_tasks = [sandbox.files.read(f.path, format=read_format(f), request_timeout=30) for f in new_files]
        downloaded_files = await asyncio.gather(*download_tasks)
        for f, content in zip(new_files, downloaded_files):
            if isinstance(content, bytes):
                # Binary files like PNG - encode as base64
                b64_data = base64.b64encode(content).decode("utf-8")
            elif Path(f.name).suffix in image_file_ext:
                # Ignore image files as they are extracted from execution results below for inline display
                b64_data = base64.b64encode(content).decode("utf-8")
            else:
                # Text files - encode utf-8 string as base64
                b64_data = content
            output_files.append({"filename": f.name, "b64_data": b64_data})

        # Collect output files from execution results
        # Respect ordering of output result types to disregard text output associated with images
        downloaded_datatypes = {f["filename"].split(".")[-1] for f in output_files}
        output_result_types = ["png", "jpeg", "svg", "text", "markdown", "json"]
        for result in execution.results:
            if getattr(result, "chart", None):
                continue
            for result_type in output_result_types:
                if b64_data := getattr(result, result_type, None):
                    if result_type in downloaded_datatypes:
                        break
                    filename = f"{HOME_DIR}/{uuid.uuid4()}.{result_type}"
                    output_files.append({"filename": filename, "b64_data": b64_data})
                    break

        # collect logs
        success = not execution.error and not execution.logs.stderr
        stdout = "\n".join(execution.logs.stdout)
        errors = "\n".join(execution.logs.stderr)
        if execution.error:
            errors = f"{execution.error}\n{errors}"

        return {
            "code": code,
            "success": success,
            "std_out": stdout,
            "std_err": errors,
            "output_files": output_files,
        }
    except Exception as e:
        return {
            "code": code,
            "success": False,
            "std_err": f"Sandbox failed to execute code: {str(e)}",
            "output_files": [],
        }


async def execute_terrarium(
    code: str,
    input_data: list[dict],
    sandbox_url: str,
) -> dict[str, Any]:
    """Execute code using Terrarium sandbox"""
    headers = {"Content-Type": "application/json"}
    data = {"code": code, "files": input_data}
    async with aiohttp.ClientSession() as session:
        async with session.post(sandbox_url, json=data, headers=headers, timeout=30) as response:
            if response.status == 200:
                result: dict[str, Any] = await response.json()
                result["code"] = code
                # Store decoded output files
                result["output_files"] = result.get("output_files", [])
                for output_file in result["output_files"]:
                    # Decode text files as UTF-8
                    if mimetypes.guess_type(output_file["filename"])[0].startswith("text/") or Path(
                        output_file["filename"]
                    ).suffix in [".org", ".md", ".json"]:
                        output_file["b64_data"] = base64.b64decode(output_file["b64_data"]).decode("utf-8")
                return result
            else:
                return {
                    "code": code,
                    "success": False,
                    "std_err": f"Failed to execute code with {response.status}",
                    "output_files": [],
                }
